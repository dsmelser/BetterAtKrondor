"""Generate placeholder C for the TASM modules linked into KRONDOR.EXE.

For every in-EXE module (see asm_publics.py) this writes port/asm/<module>.c (routines) and
<module>_data.c (data):

  * each exported routine becomes a stub that aborts with the routine's name, so
    the native link succeeds and the first call tells you what to port next;
  * each exported data symbol that the C code declares (an `extern` in a game
    header) gets a definition of the declared type, zero-initialized.

Zero-initialized data is a placeholder: the original tables (RNG state, scan-code
maps, trig and projection tables, ...) must be converted from the module's
db/dw/dd directives when the module is ported. A module whose file no longer
carries the GENERATED marker has been ported by hand and is never overwritten.

    python -I port/tools/gen_asm_stubs.py
"""

from __future__ import annotations

import os
import re
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from asm_publics import ROOT, in_exe_modules  # noqa: E402

MARKER = "GENERATED by port/tools/gen_asm_stubs.py"
NL = chr(10)
OUT_DIR = os.path.join(ROOT, "port", "asm")

# C names the native build renames (see bak_native.h).
RENAMES = {"rand": "bak_rand", "main": "bak_main"}


def header_declarations() -> dict[str, tuple[str, str]]:
    """C name -> (header path relative to bak/, declaration text without 'extern')."""
    decls: dict[str, tuple[str, str]] = {}
    for d, _, fs in os.walk(os.path.join(ROOT, "bak")):
        for f in fs:
            if os.path.splitext(f)[1].lower() != ".h":
                continue
            path = os.path.join(d, f)
            rel = os.path.relpath(path, os.path.join(ROOT, "bak")).replace(chr(92), "/")
            if rel.startswith("TOOLS/"):
                continue
            inc = rel[len("INCLUDE/"):] if rel.startswith("INCLUDE/") else rel
            text = open(path, encoding="latin-1").read()
            for m in re.finditer(r"^\s*extern\s+([^;()]*?)\b([A-Za-z_][A-Za-z0-9_]*)\s*((?:\[[^\]]*\])*)\s*;",
                                 text, re.M):
                type_, name, dims = m.group(1).strip(), m.group(2), m.group(3)
                decls.setdefault(name, (inc, f"{type_} {name}{dims}"))
            # function-pointer objects: extern T (far *name)(args);
            for m in re.finditer(r"^\s*extern\s+([^;]*?\(\s*(?:far\s*)?\*\s*([A-Za-z_][A-Za-z0-9_]*)\s*\)\s*\([^;]*\))\s*;",
                                 text, re.M):
                decls.setdefault(m.group(2), (inc, m.group(1).strip()))
    return decls


def generate() -> None:
    os.makedirs(OUT_DIR, exist_ok=True)
    decls = header_declarations()
    written = skipped = 0
    for mod in in_exe_modules():
        code = [s for s in mod.symbols if s.kind == "code"]
        data = [s for s in mod.symbols if s.kind == "data" and s.c_name in decls]
        stem = mod.name.lower()
        files = {}
        head = [
            "/*",
            f" * {MARKER} from {mod.path}.",
            " * Placeholders only: routines abort with their name, data is zero-initialized.",
            " * Replace with a C translation of the module (and drop this marker).",
            " */",
        ]
        # Routines and data live in separate files: the data needs the game headers,
        # whose real prototypes would clash with the signature-agnostic stubs.
        body = ['#include "bak_port.h"', ""]
        for s in code:
            name = RENAMES.get(s.c_name, s.c_name)
            body += [f"void {name}(void);", f"void {name}(void) {{",
                     f'    BAK_UNIMPLEMENTED("{os.path.basename(mod.path)}: {s.c_name}");', "}", ""]
        if not code and not data:
            body += ["/* Exports nothing the C code uses (a link-order anchor). */", ""]
        if code or not data:
            files[stem + ".c"] = head + body
        if data:
            headers = sorted({decls[s.c_name][0] for s in data})
            dbody = ['#include "bak_game_begin.h"', '#include "structs.h"']
            dbody += [f'#include "{h}"' for h in headers if h != "structs.h"]
            dbody += ['#include "bak_game_end.h"', ""]
            dbody += [decls[s.c_name][1] + ";" for s in data] + [""]
            files[stem + "_data.c"] = head + dbody
        for fname, lines in files.items():
            out = os.path.join(OUT_DIR, fname)
            if os.path.exists(out) and MARKER not in open(out, encoding="latin-1").read():
                skipped += 1
                continue
            with open(out, "w", encoding="latin-1", newline=NL) as f:
                f.write(NL.join(lines))
            written += 1
    print(f"wrote {written} stub files to port/asm/, kept {skipped} hand-ported")


if __name__ == "__main__":
    generate()
