"""Write port/tests/unit/tone_ogg.h: two short Ogg Vorbis tones the CD's unit tests decode.

    uv run --no-project --with soundfile --with numpy python -I port/tools/gen_tone_ogg.py

Half a second each at 44100 Hz: a stereo one (441 Hz at half scale on the left, 882 Hz at a
quarter on the right) and a mono one (441 Hz at half scale). Vorbis is lossy and its encoder's
output varies with the version, so the tests check levels, not samples. Synthetic: no game data.
"""

from __future__ import annotations

import io
from pathlib import Path

import numpy as np
import soundfile as sf

OUT = Path(__file__).resolve().parents[1] / "tests" / "unit" / "tone_ogg.h"
RATE = 44100


def ogg(pcm: np.ndarray) -> bytes:
    buf = io.BytesIO()
    sf.write(buf, pcm, RATE, format="OGG", subtype="VORBIS")
    return buf.getvalue()


def c_array(name: str, data: bytes) -> str:
    rows = [", ".join(f"0x{b:02x}" for b in data[i : i + 16]) for i in range(0, len(data), 16)]
    return (
        f"static const unsigned char {name}[{len(data)}] = {{\n    "
        + ",\n    ".join(rows)
        + ",\n};\n"
    )


def main() -> None:
    t = np.arange(RATE // 2) / RATE
    left = 0.5 * np.sin(2 * np.pi * 441 * t)
    right = 0.25 * np.sin(2 * np.pi * 882 * t)
    stereo = ogg(np.stack([left, right], axis=1).astype(np.float32))
    mono = ogg(left.astype(np.float32))
    OUT.write_text(
        "/* Generated by port/tools/gen_tone_ogg.py: half a second of 441 Hz at half scale (left;\n"
        " * the mono one) and 882 Hz at a quarter (right), Ogg Vorbis at 44100 Hz. */\n"
        + c_array("s_toneStereo", stereo)
        + c_array("s_toneMono", mono),
        encoding="utf-8",
        newline="\n",
    )
    print(f"{OUT}: stereo {len(stereo)} bytes, mono {len(mono)} bytes")


if __name__ == "__main__":
    main()
