/* The cosine of a 12-bit angle: the table covers half a turn, the other half folds onto it. */
static short cos12(u16 idx) {
    if (idx & 0x800)
        idx = (u16)(0x1000 - idx);
    return (short)s_cos[idx];
}

short r3d_tbl_sin(s16 angle) {
    return cos12((u16)((u16)angle + 0xc000) >> 4);
}

short r3d_tbl_cos(s16 angle) {
    return cos12((u16)angle >> 4);
}

/* An angle with the sign of sin_value; the table holds the first quadrant. */
s16 r3d_tbl_asin(s16 sin_value) {
    s16 v = sin_value < 0 ? (s16)-sin_value : sin_value;
    u16 idx = (u16)(v >> 5);
    if (idx >= 0x201)
        BAK_UNIMPLEMENTED("r3d_tbl_asin past +-1.0 (the original reads the code after its table)");
    u16 angle = s_asin[idx];
    if (sin_value < 0)
        angle = (u16)(0x1000 - angle);
    return (s16)(angle << 4);
}

/* The bearing of (x, y): 0 along +y, 4000h along +x (y = 0), 8000h along -y; (0, 0) gives 0.
 * The first-octant table, read with the smaller coordinate over the larger, folds across the
 * diagonal and both axes. */
s16 r3d_tbl_atan2(s16 y, s16 x) {
    u16 ay = y < 0 ? (u16) - (u16)y : (u16)y;
    u16 ax = x < 0 ? (u16) - (u16)x : (u16)x;
    u16 angle;
    if (ay == 0) {
        if (ax == 0)
            return 0;
        angle = 0x400;
    } else if (ax == 0) {
        angle = 0;
    } else if (ay == ax) {
        angle = 0x200;
    } else if (ay < ax) {
        angle = (u16)(0x400 - s_atan[((u32)ay << 9) / ax]);
    } else {
        angle = s_atan[((u32)ax << 9) / ay];
    }
    if (y < 0)
        angle = (u16)(0x800 - angle);
    if (x < 0)
        angle = (u16)(0x1000 - angle);
    return (s16)(angle << 4);
}

short r3d_tbl_atan_lookup_raw(s16 idx) {
    if ((u16)idx >= 0x200)
        BAK_UNIMPLEMENTED("r3d_tbl_atan_lookup_raw past its table (the original reads code there)");
    return (short)s_atan[idx];
}
